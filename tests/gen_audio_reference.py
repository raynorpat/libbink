#!/usr/bin/env python3
"""Generate FNV-1a checksums from captured Bink audio.

Usage: gen_audio_reference.py file [...]

Each input is raw little-endian s16, or a WAV file whose data chunk is
that PCM. The whole stream is hashed, and so is the file's frame-0 prefix.
"""

import os
import struct
import sys

FNV_OFFSET = 14695981039346656037
FNV_PRIME = 1099511628211
FRAME0_BYTES = {
    "logo_lucas.bik": 134400,
    "valve.bik": 138240,
    "original.bik": 138240,
}


def fnv1a(data):
    h = FNV_OFFSET
    for byte in data:
        h ^= byte
        h = (h * FNV_PRIME) & 0xFFFFFFFFFFFFFFFF
    return h


def pcm_payload(blob):
    if blob[:4] != b"RIFF" or blob[8:12] != b"WAVE":
        return blob
    pos = 12
    while pos + 8 <= len(blob):
        chunk_id = blob[pos:pos + 4]
        chunk_size = struct.unpack_from("<I", blob, pos + 4)[0]
        start = pos + 8
        if chunk_id == b"data":
            return blob[start:start + chunk_size]
        pos = start + chunk_size + (chunk_size & 1)
    raise ValueError("WAV file has no data chunk")


def movie_name(path):
    name = os.path.basename(path)
    for suffix in (".s16le", ".wav", ".pcm"):
        if name.endswith(suffix):
            return name[:-len(suffix)]
    return name


def main(argv):
    if len(argv) < 2:
        sys.stderr.write("usage: gen_audio_reference.py file [...]\n")
        return 2

    entries = []
    for path in argv[1:]:
        name = movie_name(path)
        if name not in FRAME0_BYTES:
            sys.stderr.write("unknown movie %s\n" % name)
            return 1
        with open(path, "rb") as stream:
            pcm = pcm_payload(stream.read())
        frame0 = FRAME0_BYTES[name]
        if len(pcm) == 0 or len(pcm) % 4 != 0 or frame0 >= len(pcm):
            sys.stderr.write(
                "%s: pcm_bytes=%d frame0_bytes=%d\n" % (name, len(pcm), frame0))
            return 1
        entries.append((name, len(pcm), fnv1a(pcm), frame0, fnv1a(pcm[:frame0])))

    out = sys.stdout
    out.write("/* Generated by tests/gen_audio_reference.py - do not edit. */\n")
    out.write("#ifndef LIBBINK_REFERENCE_AUDIO_H\n")
    out.write("#define LIBBINK_REFERENCE_AUDIO_H\n\n")
    out.write("#include <stdint.h>\n\n")
    out.write("struct reference_audio {\n")
    out.write("    const char *file;\n")
    out.write("    unsigned long pcm_bytes;\n")
    out.write("    uint64_t hash;\n")
    out.write("    unsigned long frame0_bytes;\n")
    out.write("    uint64_t frame0_hash;\n")
    out.write("};\n\n")
    out.write("static const struct reference_audio reference_audio[] = {\n")
    for name, pcm_bytes, digest, frame0, frame0_hash in entries:
        out.write('    {"%s", %dUL, UINT64_C(%d), %dUL, UINT64_C(%d)},\n'
                  % (name, pcm_bytes, digest, frame0, frame0_hash))
    out.write("};\n\n")
    out.write("#endif\n")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
