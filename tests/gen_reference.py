#!/usr/bin/env python3
"""Generate FNV-1a reference checksums from YUV4MPEG2 captures.

Usage: gen_reference.py file1.yuv [file2.yuv ...]

Each input is a YUV4MPEG2 file with I420 frames. For every input, the
planes at frame indices 0, 1, 2, 5 and 10 (when present) are hashed.
"""

import os
import sys

FNV_OFFSET = 14695981039346656037
FNV_PRIME = 1099511628211
FRAME_INDICES = (0, 1, 2, 5, 10)


def fnv1a(data):
    h = FNV_OFFSET
    for byte in data:
        h ^= byte
        h = (h * FNV_PRIME) & 0xFFFFFFFFFFFFFFFF
    return h


def parse_header(line):
    if not line.startswith(b"YUV4MPEG2 "):
        raise ValueError("not a YUV4MPEG2 stream")
    width = height = None
    for field in line.split()[1:]:
        if field[:1] == b"W":
            width = int(field[1:])
        elif field[:1] == b"H":
            height = int(field[1:])
    if width is None or height is None:
        raise ValueError("missing W/H in YUV4MPEG2 header")
    return width, height


def read_exact(stream, size):
    data = stream.read(size)
    if len(data) != size:
        raise EOFError
    return data


def parse_capture(path):
    width = height = None
    frames = []
    with open(path, "rb") as stream:
        line = stream.readline()
        if not line:
            return None
        width, height = parse_header(line)
        cw = (width + 1) // 2
        ch = (height + 1) // 2
        y_size = width * height
        c_size = cw * ch
        while True:
            frame_header = stream.readline()
            if not frame_header:
                break
            if not frame_header.startswith(b"FRAME"):
                raise ValueError("bad FRAME header in %s" % path)
            try:
                y = read_exact(stream, y_size)
                u = read_exact(stream, c_size)
                v = read_exact(stream, c_size)
            except EOFError:
                break
            frames.append((y, u, v))
    return width, height, frames


def main(argv):
    if len(argv) < 2:
        sys.stderr.write("usage: gen_reference.py file.yuv [...]\n")
        return 2

    entries = []
    for path in argv[1:]:
        parsed = parse_capture(path)
        if parsed is None:
            continue
        width, height, frames = parsed
        name = os.path.basename(path)
        if name.endswith(".yuv"):
            name = name[:-4]
        for index in FRAME_INDICES:
            if index >= len(frames):
                continue
            y, u, v = frames[index]
            entries.append((name, index, width, height,
                            fnv1a(y), fnv1a(u), fnv1a(v)))

    out = sys.stdout
    out.write("/* Generated by tests/gen_reference.py - do not edit. */\n")
    out.write("#ifndef LIBBINK_REFERENCE_CHECKSUMS_H\n")
    out.write("#define LIBBINK_REFERENCE_CHECKSUMS_H\n\n")
    out.write("#include <stdint.h>\n\n")
    out.write("struct reference_frame {\n")
    out.write("    const char *file;\n")
    out.write("    unsigned long frame;\n")
    out.write("    unsigned long width;\n")
    out.write("    unsigned long height;\n")
    out.write("    uint64_t y_hash;\n")
    out.write("    uint64_t u_hash;\n")
    out.write("    uint64_t v_hash;\n")
    out.write("};\n\n")
    out.write("static const struct reference_frame reference_frames[] = {\n")
    for name, index, width, height, y_hash, u_hash, v_hash in entries:
        out.write('    {"%s", %d, %d, %d,\n'
                  '     UINT64_C(%d), UINT64_C(%d), UINT64_C(%d)},\n'
                  % (name, index, width, height, y_hash, u_hash, v_hash))
    out.write("};\n\n")
    out.write("static const unsigned long reference_frame_count = %d;\n\n"
              % len(entries))
    out.write("#endif\n")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
